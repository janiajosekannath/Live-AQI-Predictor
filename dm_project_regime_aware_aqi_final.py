def mine_smog_rules(tdf, min_support, targets, max_len=4):
    fi = fpgrowth(tdf, min_support=min_support, use_colnames=True, max_len=max_len)
    if fi.empty:
        return pd.DataFrame(columns=["Antecedent", "Consequent", "support", "confidence", "lift"])
    r = association_rules(fi, metric="lift", min_threshold=1.0)
    r = r[r["consequents"].apply(lambda x: len(x) == 1 and next(iter(x)) in targets)]
    r = r[~r["antecedents"].apply(lambda x: any(i.startswith("AQI_") for i in x))].copy()
    r["Antecedent"] = r["antecedents"].apply(lambda x: " + ".join(sorted(x)))
    r["Consequent"] = r["consequents"].apply(lambda x: next(iter(x)))
    r["Has_Context"] = r["antecedents"].apply(
        lambda x: any(i.startswith(("City_", "Season_")) for i in x))
    return (r[["Antecedent", "Consequent", "support", "confidence", "lift", "Has_Context"]]
            .sort_values(["lift", "confidence", "support"], ascending=False)
            .reset_index(drop=True))

